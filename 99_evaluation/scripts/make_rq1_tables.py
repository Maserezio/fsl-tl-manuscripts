"""Build the RQ1 result tables from the evaluation CSVs, as Markdown and LaTeX.

One generator for both formats so the two can never drift apart. Re-run it whenever
a new evaluation lands; nothing here trains or scores anything, it only aggregates
what is already on disk.

    python 99_evaluation/scripts/make_rq1_tables.py

Writes  RQ1_ALL_RESULTS.md   (reading copy)
        RQ1_ALL_RESULTS.tex  (thesis fragment: \\input{} it, see PREAMBLE below)

Three cell states, and the difference matters when reading the tables:
    number  -- scored
    TBD     -- the model is trained, its metrics were never computed
    ---     -- no model: that run was never launched

Which state a cell gets is decided from the filesystem, not from a hand-written
list: the trained set comes from scanning for best.pth / trained detector dirs, the
scored set from the metric CSVs. So a table can only overstate what exists if the
weights themselves are stale.
"""

import csv
import re
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[2]
EVAL = REPO / "99_evaluation"
SUMMARY = EVAL / "summaries"
OUT_MD = SUMMARY / "rq1" / "RQ1_ALL_RESULTS.md"
OUT_TEX = SUMMARY / "rq1" / "RQ1_ALL_RESULTS.tex"
KSHOT_CSV = SUMMARY / "rq2" / "kshot_cb55.csv"

METRICS = ["Pixel_IU", "Line_IU", "DR", "RA", "FM"]
DASH_MD, TBD = "—", "TBD"
DASH_TEX = "---"

# Size brackets by encoder parameter count.
BRACKET = {
    "XS": ["convnext_femto", "pvt_v2_b0", "vit_tiny"],
    "S": ["convnext_pico", "pvt_v2_b1"],
    "M": ["convnext_tiny", "pvt_v2_b2", "vit_small", "resnet34", "resnet50",
          "dinov2", "dinov2_reg", "stock r50vd"],
}
PARAMS = {"convnext_femto": "4.83M", "pvt_v2_b0": "3.41M", "vit_tiny": "5.5M",
          "convnext_pico": "8.53M", "pvt_v2_b1": "13.5M", "convnext_tiny": "27.8M",
          "pvt_v2_b2": "24.9M", "vit_small": "21.7M", "resnet34": "21.3M",
          "resnet50": "23.5M", "dinov2": "21.7M", "dinov2_reg": "21.7M",
          "stock r50vd": "23.5M"}
FAMILY = {"convnext_femto": "CNN", "convnext_pico": "CNN", "convnext_tiny": "CNN",
          "resnet34": "CNN", "resnet50": "CNN", "stock r50vd": "CNN",
          "pvt_v2_b0": "ViT", "pvt_v2_b1": "ViT", "pvt_v2_b2": "ViT",
          "vit_tiny": "ViT", "vit_small": "ViT", "dinov2": "ViT", "dinov2_reg": "ViT"}
INITS = ["random", "imagenet", "ssl"]
SUBSETS = {"DIVA-HisDB": ["CB55", "CS18", "CS863"],
           "U-DIADS-TL": ["Latin14396", "Latin2", "Syr341"]}

# The single two-stage cell per subset that went through the tuned-postprocessing study.
TUNED_CELL = {"Latin14396": ("convnext_tiny", "imagenet"),
              "Latin2": ("stock r50vd", "random"),
              "Syr341": ("convnext_tiny", "ssl")}

PREAMBLE = r"""% Requires: \usepackage{booktabs,longtable,array}
% Generated by 99_evaluation/scripts/make_rq1_tables.py -- do not edit by hand."""


def canonical(encoder):
    """Encoder name as it appears in the tables (timm/smp prefixes and tags dropped)."""
    encoder = encoder.replace("tu-", "")
    if encoder.startswith("stock"):
        return "stock r50vd"
    for key in sorted(PARAMS, key=len, reverse=True):
        if key in encoder:
            return key
    return encoder


# --------------------------------------------------------------------------- data


def simple_trained():
    """(dataset, model, init, subset) for every one-stage checkpoint on disk."""
    out = set()
    for path in (REPO / "80_models/semantic_segmentation/unet").rglob("best.pth"):
        name = path.parent.name
        # Side experiments, not part of the size axis: skip-connection ablation,
        # DPT decoders, and the duplicate 50-epoch DIVA runs.
        if name.startswith(("skipabl_", "simple_segmentation_", "dpt_")):
            continue
        match = re.match(r"unet_(.+)_(udiads|diva)_([A-Za-z0-9]+)$", name)
        if not match:
            continue
        encoder, family, subset = match.groups()
        if subset.endswith("50ep"):
            continue
        dataset = "U-DIADS-TL" if family == "udiads" else "DIVA-HisDB"
        if encoder.endswith("_szrand"):
            init, encoder = "random", encoder[:-len("_szrand")]
        elif encoder.endswith("_sz"):
            init, encoder = "imagenet", encoder[:-len("_sz")]
        elif "dinov3" in encoder or encoder in ("dinov2", "dinov2_reg"):
            init = "ssl"
        else:
            init = "imagenet"
        out.add((dataset, canonical(encoder), init, subset))
    return out


def simple_scored():
    udiads = pd.read_csv(EVAL / "semantic_segmentation/unet/u-diads-tl/size_axis_zottin.csv")
    udiads["model"] = udiads.encoder.map(canonical)
    udiads["init"] = udiads.init.replace({"dinov3": "ssl"})
    udiads["dataset"] = "U-DIADS-TL"
    diva = pd.read_csv(
        SUMMARY / "diagnostics" / "simple_segmentation" / "diva_backbone_matrix.csv"
    )
    diva["init"] = diva.encoder.map(
        lambda e: "ssl" if ("dinov3" in e or "dinov2" in e) else "imagenet")
    diva["model"] = diva.encoder.map(canonical)
    diva["dataset"] = "DIVA-HisDB"
    cols = ["dataset", "model", "init", "subset"] + METRICS
    return pd.concat([udiads[cols], diva[cols]], ignore_index=True)


def detectors_trained():
    """(dataset, subset, model, init) for every trained two-stage detector."""
    out = set()
    sources = [("U-DIADS-TL", EVAL / "instance_segmentation/rtdetr_bbox_unet/u-diads-tl/rtdetr_hf",
                ["Latin14396", "Latin2", "Syr341"]),
               ("DIVA-HisDB", EVAL / "instance_segmentation/rtdetr_bbox_unet/diva-hisdb/rtdetr_hf",
                ["", "CS863", "CS18"])]
    for dataset, base, subsets in sources:
        for subset in subsets:
            rows = list(csv.reader(open(base / subset / "results.csv")))
            index = {k: i for i, k in enumerate(rows[0])}
            for row in rows[1:]:
                if "init" in index and row[index["init"]]:
                    init = row[index["init"]]
                    backbone = row[index["backbone"]].split(" (")[0]
                else:
                    # Pre-schema rows from the first CB55 experiments.
                    name = row[index["platform"]]
                    if name in ("rfdetr", "rtdetr", "rfdetr_hf") or name.startswith("rtdetr_bb_"):
                        continue
                    init = ("dinov3" if "dinov3" in name else
                            "imagenet" if "imagenet" in name else "random")
                    backbone = name.replace("rtdetr_", "").replace("_" + init, "")
                out.add((dataset, subset or "CB55", canonical(backbone),
                         "ssl" if init == "dinov3" else init))
    return out


def twostage_scored():
    """One row per evaluated (detector, loss, postprocessing) combination."""
    rows = []
    base = EVAL / "instance_segmentation/rtdetr_bbox_unet/u-diads-tl"
    name_of = {"latin14396": "Latin14396", "latin2": "Latin2", "syr341": "Syr341"}
    for folder in list(base.glob("*_matrix_1024x256")) + list(base.glob("*_lossabl_1024x256")):
        subset = name_of[folder.name.split("_")[0]]
        for csv_path in folder.glob("*/per_page_zottin.csv"):
            match = re.match(r"rtdetr_(.+)_(random|imagenet|dinov3)_(bce|tversky|supervoxel)$",
                             csv_path.parent.name)
            if not match:
                continue
            backbone, init, loss = match.groups()
            mean = pd.read_csv(csv_path)[METRICS].mean()
            rows.append(dict(dataset="U-DIADS-TL", subset=subset, model=canonical(backbone),
                             init="ssl" if init == "dinov3" else init,
                             loss=loss, postproc="default",
                             **{k: f"{mean[k]:.4f}" for k in METRICS}))
    for subset, (model, init) in TUNED_CELL.items():
        path = base / "postproc_tuned" / f"{subset}_final_summary.csv"
        if path.exists():
            tuned = pd.read_csv(path).set_index("setting").loc["tuned"]
            rows.append(dict(dataset="U-DIADS-TL", subset=subset, model=model, init=init,
                             loss="bce", postproc="tuned",
                             **{k: f"{tuned[k]:.4f}" for k in METRICS}))
    return pd.DataFrame(rows)


# ------------------------------------------------------------------------ writing


def kshot_curve():
    """The k-shot curve, or None if it has not been produced yet."""
    if not KSHOT_CSV.exists():
        return None
    frame = pd.read_csv(KSHOT_CSV)
    return frame.sort_values(["approach", "k"])


def cells_simple(scored, trained, dataset, model, init, subset):
    hit = scored[(scored.dataset == dataset) & (scored.model == model)
                 & (scored.init == init) & (scored.subset == subset)]
    if len(hit):
        return [f"{hit.iloc[0][k]:.4f}" for k in METRICS]
    if (dataset, model, init, subset) in trained:
        return [TBD] * 5
    return [None] * 5


def rows_twostage(scored, trained, dataset, model, init, subset):
    """-> list of (loss, postproc, [5 cells]); None cells mean 'no model'."""
    hits = scored[(scored.dataset == dataset) & (scored.model == model)
                  & (scored.init == init) & (scored.subset == subset)] if len(scored) else []
    if len(hits):
        return [(r.loss, r.postproc, [r[k] for k in METRICS])
                for _, r in hits.sort_values(["postproc", "loss"]).iterrows()]
    if (dataset, subset, model, init) in trained:
        return [(TBD, TBD, [TBD] * 5)]
    return [(None, None, [None] * 5)]


def render(fmt, simple_sc, simple_tr, two_sc, two_tr):
    """fmt is 'md' or 'tex'."""
    dash = DASH_MD if fmt == "md" else DASH_TEX
    esc = (lambda s: s) if fmt == "md" else (lambda s: str(s).replace("_", r"\_"))
    cell = lambda v: dash if v is None else esc(v)
    out = []

    if fmt == "md":
        out += ["# RQ1 — сводка всех посчитанных прогонов", "",
                "Пять официальных метрик (Zottin, `50_modelling/common/evaluate_util.py`), тестовый сплит.", "",
                "| обозначение | значение |", "|---|---|",
                "| число | посчитано |",
                "| `TBD` | модель обучена, метрики не посчитаны |",
                f"| {DASH_MD} | модели нет — прогон не запускался |", "",
                "`init`: **random** — случайная инициализация · **imagenet** — супервизное",
                "предобучение · **ssl** — самообучение (DINOv3; для `dinov2`/`dinov2_reg` — DINOv2).",
                "", "---", ""]
    else:
        out += [PREAMBLE, "",
                r"% Cell states: number = scored, TBD = trained but not scored, --- = no model.",
                ""]

    def heading(level, text):
        if fmt == "md":
            out.append(("#" * level) + " " + text)
        else:
            out.append({1: r"\section{%s}", 2: r"\subsection{%s}",
                        3: r"\subsection*{%s}"}[level] % esc(text))
        out.append("")

    def table(header, body, caption, label):
        if fmt == "md":
            out.append("| " + " | ".join(header) + " |")
            out.append("|" + "|".join(["---"] * (len(header) - 5) + ["---:"] * 5) + "|")
            out.extend("| " + " | ".join(r) + " |" for r in body)
        else:
            spec = "l" * (len(header) - 5) + "r" * 5
            out.extend([r"\begin{longtable}{%s}" % spec,
                    r"\caption{%s}\label{%s}\\" % (esc(caption), label),
                    r"\toprule",
                    " & ".join(esc(h) for h in header) + r" \\",
                    r"\midrule\endfirsthead",
                    r"\toprule",
                    " & ".join(esc(h) for h in header) + r" \\",
                    r"\midrule\endhead",
                    r"\bottomrule\endfoot"])
            out.extend(" & ".join(r) + r" \\" for r in body)
            out.append(r"\end{longtable}")
        out.append("")

    heading(1, "Simple segmentation — U-Net, одностадийная" if fmt == "md"
            else "Simple segmentation (single-stage U-Net)")
    for bracket in ("XS", "S", "M"):
        heading(2, f"Размер {bracket}" if fmt == "md" else f"Size bracket {bracket}")
        for dataset in ("DIVA-HisDB", "U-DIADS-TL"):
            models = [m for m in BRACKET[bracket]
                      if any((dataset, m, i, s) in simple_tr
                             for i in INITS for s in SUBSETS[dataset])]
            heading(3, dataset)
            if not models:
                out.extend([dash + (" нет обученных моделей" if fmt == "md" else ""), ""])
                continue
            body = []
            for model in sorted(models, key=lambda m: (FAMILY.get(m, "CNN"), m)):
                for init in INITS:
                    for subset in SUBSETS[dataset]:
                        vals = cells_simple(simple_sc, simple_tr, dataset, model, init, subset)
                        body.append([esc(model), FAMILY.get(model, dash),
                                     PARAMS.get(model, dash), init, esc(subset)]
                                    + [cell(v) for v in vals])
            table(["model", "type", "params", "init", "subset"] + METRICS,
                  body, f"Single-stage, {bracket} bracket, {dataset}",
                  f"tab:simple-{bracket.lower()}-{dataset.split('-')[0].lower()}")

    heading(1, "Two-stage — RT-DETR детектор → U-Net по кропам" if fmt == "md"
            else "Two-stage (RT-DETR detector + crop U-Net)")
    note = ("`postproc`: **default** = порог 0.5, closing 0.04; **tuned** = подобрано "
            "на валидации. Сравнимы только строки с одинаковым `postproc`."
            if fmt == "md" else
            r"Only rows sharing a \texttt{postproc} value are comparable: tuning the "
            r"postprocessing is worth between $+0.03$ and $+0.10$ FM, the more so the "
            r"denser the page.")
    out += [note, ""]
    for bracket in ("XS", "S", "M"):
        heading(2, f"Размер {bracket}" if fmt == "md" else f"Size bracket {bracket}")
        for dataset in ("DIVA-HisDB", "U-DIADS-TL"):
            models = [m for m in BRACKET[bracket]
                      if any((dataset, s, m, i) in two_tr
                             for i in INITS for s in SUBSETS[dataset])]
            heading(3, dataset)
            if not models:
                out.extend([dash + (" нет обученных детекторов" if fmt == "md" else ""), ""])
                continue
            body = []
            for model in sorted(models, key=lambda m: (FAMILY.get(m, "CNN"), m)):
                for init in INITS:
                    for subset in SUBSETS[dataset]:
                        for loss, postproc, vals in rows_twostage(
                                two_sc, two_tr, dataset, model, init, subset):
                            body.append([esc(model), FAMILY.get(model, dash),
                                         PARAMS.get(model, dash), init, esc(subset),
                                         cell(loss), cell(postproc)]
                                        + [cell(v) for v in vals])
            table(["model", "type", "params", "init", "subset", "loss", "postproc"]
                  + METRICS, body,
                  f"Two-stage, {bracket} bracket, {dataset}",
                  f"tab:two-{bracket.lower()}-{dataset.split('-')[0].lower()}")

    curve = kshot_curve()
    if curve is not None:
        heading(1, "Кривая по числу размеченных страниц (CB55)" if fmt == "md"
                else "Labeled-page budget (CB55)")
        out.extend([
            ("Один энкодер (`convnext_tiny`, imagenet) в обеих схемах. Страницы для каждого k "
             "выбирает один и тот же `few_shot_sampler`, отбор вложенный, так что точки "
             "отличаются только добавленными страницами. В двухстадийной схеме k ограничивает "
             "обе стадии.")
            if fmt == "md" else
            (r"One encoder (\texttt{convnext\_tiny}, ImageNet) in both pipelines; the k pages "
             r"come from the same nested selector, so consecutive points differ only by the "
             r"pages added. In the two-stage arm k constrains both stages."), ""])
        body = [[esc(r.approach), str(r.k)] + [f"{r[m]:.4f}" if pd.notna(r[m]) else dash
                                               for m in METRICS]
                for _, r in curve.iterrows()]
        table(["approach", "k"] + METRICS, body,
              "Five metrics against the number of labeled pages, CB55",
              "tab:kshot-cb55")
    return "\n".join(out)


def main():
    simple_tr, simple_sc = simple_trained(), simple_scored()
    two_tr, two_sc = detectors_trained(), twostage_scored()
    OUT_MD.write_text(render("md", simple_sc, simple_tr, two_sc, two_tr))
    OUT_TEX.write_text(render("tex", simple_sc, simple_tr, two_sc, two_tr))
    scored_two = sum(
        1 for c in two_tr
        if len(two_sc[(two_sc.dataset == c[0]) & (two_sc.subset == c[1])
                      & (two_sc.model == c[2]) & (two_sc.init == c[3])]))
    print(f"{OUT_MD.name}: ok")
    print(f"{OUT_TEX.name}: ok")
    print(f"simple: {len(simple_sc)} scored / {len(simple_tr)} trained")
    print(f"two-stage: {scored_two} scored / {len(two_tr)} trained detectors")


if __name__ == "__main__":
    main()
